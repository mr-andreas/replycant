// Regenerates pairing.fixture.json from the Go writer.
//
// The pairing record format is defined by pkg/pairing in the Go tree, and both
// the TypeScript and Swift readers have to match it byte for byte. Hand-written
// fixtures would only prove a reader agrees with itself, so this produces one
// with the real writer. Run `node src/lib/pairingFixture.mjs` after changing
// any of the three.
//
// The iOS test bundle gets its own copy because a simulator cannot read repo
// paths at runtime. Both copies come from this one run, so they cannot drift
// as long as the readers are tested against a freshly generated fixture.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..");

const program = `
package main

import (
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"

	"github.com/mr-andreas/replycant/pkg/pairing"
	"golang.org/x/crypto/curve25519"
)

func main() {
	privateKey := make([]byte, 32)
	if _, err := rand.Read(privateKey); err != nil {
		panic(err)
	}
	publicKey, err := curve25519.X25519(privateKey, curve25519.Basepoint)
	if err != nil {
		panic(err)
	}

	// A self-signed-looking DER stand-in is enough: VerifyCALabel only hashes
	// the bytes between the PEM markers, it never parses the certificate.
	caDER := make([]byte, 256)
	if _, err := rand.Read(caDER); err != nil {
		panic(err)
	}
	caB64 := base64.StdEncoding.EncodeToString(caDER)
	caPEM := "-----BEGIN CERTIFICATE-----\\n" + caB64 + "\\n-----END CERTIFICATE-----\\n"
	digest := sha256.Sum256(caDER)
	label := hex.EncodeToString(digest[:])[:32]

	secret, err := pairing.NewSecret()
	if err != nil {
		panic(err)
	}

	payload := pairing.Payload{
		HeadscaleURL: fmt.Sprintf("https://%s.tunnel.replycant.com", label),
		CAPEM:        caPEM,
		PreauthKey:   "fixture-preauth-key",
	}

	sealed, err := pairing.Seal(secret, publicKey, payload)
	if err != nil {
		panic(err)
	}

	// A second record under a different secret, so the reader can be shown
	// rejecting one written for another pairing attempt.
	otherSecret, err := pairing.NewSecret()
	if err != nil {
		panic(err)
	}
	otherSealed, err := pairing.Seal(otherSecret, publicKey, payload)
	if err != nil {
		panic(err)
	}

	// A record for a different device, to show the age layer is load bearing
	// and not merely along for the ride.
	otherDeviceKey := make([]byte, 32)
	if _, err := rand.Read(otherDeviceKey); err != nil {
		panic(err)
	}
	otherDevicePublic, err := curve25519.X25519(otherDeviceKey, curve25519.Basepoint)
	if err != nil {
		panic(err)
	}
	foreignSealed, err := pairing.Seal(secret, otherDevicePublic, payload)
	if err != nil {
		panic(err)
	}

	// A record whose CA does not match the fingerprint in its hostname.
	mismatched := payload
	mismatched.CAPEM = "-----BEGIN CERTIFICATE-----\\n" +
		base64.StdEncoding.EncodeToString([]byte("a different certificate entirely")) +
		"\\n-----END CERTIFICATE-----\\n"
	mismatchedSealed, err := pairing.Seal(secret, publicKey, mismatched)
	if err != nil {
		panic(err)
	}

	// Manual-exposure mode: an operator-chosen hostname commits to no CA.
	manual := payload
	manual.HeadscaleURL = "https://headscale.example.com"
	manualSealed, err := pairing.Seal(secret, publicKey, manual)
	if err != nil {
		panic(err)
	}

	out, err := json.MarshalIndent(map[string]any{
		"comment":               "Generated by src/lib/pairingFixture.mjs from the Go pkg/pairing writer. Do not edit by hand.",
		"secret":                secret.String(),
		"slot":                  secret.Slot(),
		"otherSecret":           otherSecret.String(),
		"agePrivateKeyBase64":   base64.StdEncoding.EncodeToString(privateKey),
		"agePublicKeyBase64":    base64.StdEncoding.EncodeToString(publicKey),
		"caLabel":               label,
		"payload":               payload,
		"sealedBase64":          base64.StdEncoding.EncodeToString(sealed),
		"otherSecretSealedBase64": base64.StdEncoding.EncodeToString(otherSealed),
		"foreignDeviceSealedBase64": base64.StdEncoding.EncodeToString(foreignSealed),
		"mismatchedCaSealedBase64":  base64.StdEncoding.EncodeToString(mismatchedSealed),
		"manualModeSealedBase64":    base64.StdEncoding.EncodeToString(manualSealed),
	}, "", "  ")
	if err != nil {
		panic(err)
	}
	os.Stdout.Write(out)
}
`;

const generatorDir = join(repoRoot, "webapp", "sidecar", "build", "pairingfixture");
spawnSync("mkdir", ["-p", generatorDir]);
writeFileSync(join(generatorDir, "main.go"), program);

const result = spawnSync("go", ["run", "./webapp/sidecar/build/pairingfixture"], {
  cwd: repoRoot,
  encoding: "utf8",
});
if (result.status !== 0) {
  console.error(result.stderr);
  process.exit(1);
}

writeFileSync(join(here, "pairing.fixture.json"), `${result.stdout}\n`);
console.log("wrote src/lib/pairing.fixture.json");

const iosFixture = join(repoRoot, "iosapp", "iosappTests", "Fixtures", "pairing.fixture.json");
spawnSync("mkdir", ["-p", dirname(iosFixture)]);
writeFileSync(iosFixture, `${result.stdout}\n`);
console.log("wrote iosapp/iosappTests/Fixtures/pairing.fixture.json");
